	//////////////////////// DOWNLOADING ///////////////////////////

	wire dio_download = ioctl_download;
	wire [23:0] dio_addr = ioctl_addr[24:1];
	wire [7:0] dio_index = ioctl_index;
	// mirror of MacIIvi.sv: Main packs the matched extension into the upper
	// ioctl_index bits — compare only the MENU index (see MacIIvi.sv rationale)
	wire [5:0] dio_menu = dio_index[5:0];

	// Floppy disk image tracking (single drive — mirror of MacIIvi.sv)
	reg dsk_int_ds;
	reg dsk_int_ss;
	reg dsk_int_mfm;  // MFM-format image (ISM path): 720K or 1.44MB
	reg dsk_int_hd;   // 1.44MB HD (vs 720K DD)
	// DiskCopy 4.2 header skip — mirror of MacIIvi.sv (rationale there).
	reg dc42_name_ok;
	reg dc42_skip;
	reg [7:0] dc42_disk_format;    // DC42 byte 0x50: 0/1/2/3 = 400G/800G/720M/1440M
	// Disk-change presentation — mirror of MacIIvi.sv (full rationale there): a
	// swap must reach the guest as eject THEN insert, because it only learns
	// about media by polling CSTIN. The sim mounts one image and never swaps,
	// so this only delays that mount; it is here to keep the two tops from
	// diverging.
	localparam [25:0] DSK_EMPTY_CY = 26'h3FFFFFF;
	reg [25:0] dsk_int_empty_cy;
	wire dsk_int_empty = (dsk_int_empty_cy != DSK_EMPTY_CY);
	wire dsk_int_ins = !dsk_int_empty && (dsk_int_ds || dsk_int_ss || dsk_int_mfm);

	always @(posedge clk_sys) begin
		reg old_down;
		old_down <= dio_download;
		if(~old_down && dio_download && dio_menu == 6'd1) begin
			dsk_int_ds  <= 0;
			dsk_int_ss  <= 0;
			dsk_int_mfm <= 0;
			dsk_int_hd  <= 0;
			dsk_int_empty_cy <= 26'd0;
		end
		else if(dio_download && dio_menu == 6'd1)
			dsk_int_empty_cy <= 26'd0;
		else if(dsk_int_empty_cy != DSK_EMPTY_CY)
			dsk_int_empty_cy <= dsk_int_empty_cy + 26'd1;
		if(old_down && ~dio_download && dio_menu == 6'd1) begin
			dsk_int_ds <= (dio_addr == 409600) ||
			              (dc42_skip && (dio_addr == 409642 || dio_addr == 419242));
			dsk_int_ss <= (dio_addr == 204800) ||
			              (dc42_skip && (dio_addr == 204842 || dio_addr == 209642));
			dsk_int_mfm <= (dio_addr == 368640) || (dio_addr == 737280) ||
			               (dc42_skip && (dc42_disk_format == 8'd2 || dc42_disk_format == 8'd3));
			dsk_int_hd  <= (dio_addr == 737280) ||
			               (dc42_skip && dc42_disk_format == 8'd3);
			$display("SIM: floppy0 download end dio_addr(words)=%0d dc42=%b fmt=%02x -> ds=%b ss=%b mfm=%b hd=%b",
			         dio_addr, dc42_skip, dc42_disk_format,
			         (dio_addr == 409600) || (dc42_skip && (dio_addr == 409642 || dio_addr == 419242)),
			         (dio_addr == 204800) || (dc42_skip && (dio_addr == 204842 || dio_addr == 209642)),
			         (dio_addr == 368640) || (dio_addr == 737280) || (dc42_skip && (dc42_disk_format == 8'd2 || dc42_disk_format == 8'd3)),
			         (dio_addr == 737280) || (dc42_skip && dc42_disk_format == 8'd3));
		end
		if(diskEject[0]) begin
			dsk_int_ds <= 0;
			dsk_int_ss <= 0;
			dsk_int_mfm <= 0;
			dsk_int_hd <= 0;
		end
	end

	// (the dsk_ext_* mount block was removed with the second floppy —
	// mirror of MacIIvi.sv; diskEject[1] intentionally lands nowhere)

	// Download addresses (SDRAM word addresses, VASP layout):
	//   ROM (1MB): $000000 + offset
	//   Floppy:    $180000 + offset
	//   ($280000, the old Floppy-2 staging region, is unused since the
	//    second drive was dropped — index 2 can no longer arrive.)
	reg [25:0] dio_a;
	reg [15:0] dio_data;
	reg        dio_write;
	reg        dio_old_cyc = 0;

	// DC42 write offset: active from the word after the magic (word 41)
	wire [19:0] dio_flp_a = dc42_skip ? (dio_addr[19:0] - 20'd42) : dio_addr[19:0];

	always @(posedge clk_sys) begin
		if(ioctl_wr) begin
			if (dio_index[1:0] != 2'b00) begin
				// accept either byte lane order for the sim stream
				if (dio_addr[19:0] == 20'd0) begin
					dc42_skip    <= 1'b0;
					dc42_name_ok <= ((ioctl_dout[7:0]  >= 8'd1) && (ioctl_dout[7:0]  <= 8'd63)) ||
					                ((ioctl_dout[15:8] >= 8'd1) && (ioctl_dout[15:8] <= 8'd63));
				end else if (dio_addr[19:0] == 20'd40)
					dc42_disk_format <= ioctl_dout[7:0];  // byte 0x50 (low byte of word 40)
				else if (dio_addr[19:0] == 20'd41 && dc42_name_ok &&
				             (ioctl_dout == 16'h0001 || ioctl_dout == 16'h0100))
					dc42_skip <= 1'b1;
			end
			// Don't byte-swap for sim_ram (original swaps for SDRAM byte ordering)
			dio_data <= ioctl_dout;
			case (dio_index[1:0])
				2'b01:   dio_a <= 26'h0180000 + {6'b0, dio_flp_a};  // Floppy
				default: dio_a <= {7'b0, dio_addr[18:0]};           // ROM (1MB) at $000000 (must match addrController rom_sdram_word)
			endcase
			ioctl_wait <= 1;
		end

		dio_old_cyc <= dioBusControl;
		if(~dioBusControl) dio_write <= ioctl_wait;
		if(dio_old_cyc & ~dioBusControl & dio_write) ioctl_wait <= 0;
	end

	////////////////////////// RAM /////////////////////////////////

	// For simulation with synchronous RAM, use simplified direct download path
	wire download_cycle = dio_download && ioctl_wr;

	// SDRAM word address mapping (VASP layout — docs/VASP_RETARGET.md):
	// memoryAddr[25:0] is already the SDRAM word address from addrController.
	// Download path uses dio_a_comb directly.
	wire [25:0] dio_a_comb;
	assign dio_a_comb = (ioctl_index[1:0] == 2'b01) ? 26'h0180000 + {6'b0, ioctl_addr[20:1]} :  // Floppy
	                    {7'b0, ioctl_addr[19:1]};                                                 // ROM (1MB) at $000000 (must match addrController rom_sdram_word)

	// Card cold-tail (ext) SDRAM access — twin of MacIIvi.sv. The card's ext
	// port owns card words [196608, 524288) at SDRAM word $100000 + word
	// (= $130000..$17FFFF inside the reserved mdc824 window). An ext access
	// coincides with a CPU bus cycle TO the card, so the cpu RAM/ROM arms
	// are idle by construction; only floppy staging can collide, and then
	// the ext op just waits (the ready counter only advances on presented
	// cycles). Priority: download > floppy staging > card ext > cpu.
	wire [25:0] card_ext_addr = 26'h0100000 + {6'd0, mdc_vram_addr[19:0]};
	wire        card_ext_req  = card_ext_rd || card_ext_wr;
	wire        card_ext_slot = card_ext_req && !download_cycle
	                            && !dskReadAckInt && !dskReadAckExt;
	reg  [1:0]  card_ext_cnt = 2'd0;
	always @(posedge clk_sys) begin
		if (!card_ext_req)
			card_ext_cnt <= 2'd0;
		else if (card_ext_slot && card_ext_cnt != 2'd3)
			card_ext_cnt <= card_ext_cnt + 2'd1;
	end
	assign card_ext_ready = (card_ext_cnt == 2'd3);
	assign card_ext_din   = ram_do_raw;

	wire [25:0] ram_addr = download_cycle ? dio_a_comb :
	                       card_ext_slot  ? card_ext_addr : memoryAddr;

	// Use ioctl_dout directly for download (bypass registered dio_data)
	wire [15:0] ram_din  = download_cycle ? ioctl_dout :
	                       card_ext_slot  ? mdc_vram_dout : memoryDataOut;
	wire  [1:0] ram_ds   = download_cycle ? 2'b11 :
	                       card_ext_slot  ? 2'b11 : { !_memoryUDS, !_memoryLDS };
	// Use ioctl_wr directly as write enable during download (bypass registered dio_write)
	wire        ram_we   = download_cycle ? 1'b1 :
	                       card_ext_slot  ? card_ext_wr : !_ramWE;
	wire        ram_oe   = download_cycle ? 1'b0 :
	                       card_ext_slot  ? card_ext_rd :
	                       (!_ramOE || !_romOE || dskReadAckInt || dskReadAckExt);
	wire [15:0] ram_do_raw;
	// (LC II warm-vs-cold ROM patch retired — see MacIIvi.sv note / VASP_RETARGET.md.)
	wire [15:0] ram_do   = download_cycle ? 16'hffff : (dskReadAckInt || dskReadAckExt) ? extra_rom_data_demux : ram_do_raw;
	// Disk byte-parity select: must be dskReadAddr[0], NOT memoryAddr[0] (which
	// is dskReadAddr[1] after the >>1 word conversion drops bit 0). See the long
	// note at the matching demux in MacIIvi.sv — the old bit selected the wrong
	// byte on odd addresses and corrupted every floppy sector. Keep in sync.
	wire dsk_byte_odd = dskReadAckExt ? dskReadAddrExt[0] : dskReadAddrInt[0];
	wire [15:0] extra_rom_data_demux = dsk_byte_odd ?
						   {ram_do_raw[7:0],ram_do_raw[7:0]}:{ram_do_raw[15:8],ram_do_raw[15:8]};

	sim_ram ram
	(
		.clk            ( clk_sys     ),
		.reset          ( reset       ),
		.din            ( ram_din     ),
		.addr           ( ram_addr    ),
		.ds             ( ram_ds      ),
		.we             ( ram_we      ),
		.oe             ( ram_oe      ),
		.dout           ( ram_do_raw  ),
		.module_sz      ( cfg_sdramMod ),
		.frame_count    ( sim_frame_count )
	);


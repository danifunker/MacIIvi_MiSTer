`timescale 1ns / 1ps
//============================================================================
//  Macintosh IIvi - Verilator Simulation Wrapper
//
//  Adapted from MacIIvi.sv for simulation
//============================================================================

module emu
(
	input         clk_sys,
	input         reset,

	// PS2 keyboard/mouse
	input [10:0]  ps2_key,
	input [24:0]  ps2_mouse,

	// RTC timestamp
	input [32:0]  timestamp,

	// VGA output
	output [7:0]  VGA_R,
	output [7:0]  VGA_G,
	output [7:0]  VGA_B,
	output        VGA_HS,
	output        VGA_VS,
	output        VGA_HB,
	output        VGA_VB,
	output        CE_PIXEL,

	// Audio output
	output [15:0] AUDIO_L,
	output [15:0] AUDIO_R,

	// ROM/disk loading interface (ioctl)
	input         ioctl_download,
	input         ioctl_wr,
	input [24:0]  ioctl_addr,
	input [15:0]  ioctl_dout,
	input [7:0]   ioctl_index,
	output reg    ioctl_wait = 1'b0,

	// SCSI block device interface. Slots: 0,1 = disks (SCSI 0/1),
	// 2 = CD-ROM (SCSI 3; FPGA top uses hps_io slot 3 for it — the sim
	// block-device model has no PRAM slot so the CD sits at 2).
	output [31:0] sd_lba[3],
	output [2:0]  sd_rd,
	output [2:0]  sd_wr,
	input  [2:0]  sd_ack,
	input  [7:0]  sd_buff_addr,
	input  [15:0] sd_buff_dout,
	output [15:0] sd_buff_din[3],
	input         sd_buff_wr,
	input  [2:0]  img_mounted,
	input  [63:0] img_size,

	// CPU debug outputs
	output [31:0] debug_pc,
	output [15:0] debug_opcode,
	output        debug_fetch_valid,
	output [31:0] debug_data_addr,

	// RAM debug outputs
	output [25:0] debug_ram_addr,
	output [15:0] debug_ram_din,
	output [15:0] debug_ram_dout,
	output        debug_ram_we,
	output        debug_ram_oe,
	output  [1:0] debug_ram_ds,
	output        debug_selectRAM,
	output        debug_selectROM,

	// Peripheral debug outputs
	output        debug_selectVIA,
	output        debug_selectAriel,
	output        debug_selectPseudoVIA,
	output        debug_selectSCSI,
	output        debug_selectSCC,
	output        debug_selectIWM,
	output        debug_selectASC,
	output        debug_selectVRAM,
	output [31:0] debug_cpuAddr,
	output [15:0] debug_cpuDataIn,    // Data from CPU to peripherals
	output [15:0] debug_cpuDataOut,   // Data from peripherals to CPU
	output        debug_cpuRW,        // 1=read, 0=write
	output        debug_cpuBusControl,
	output        debug_cpu_as,       // _cpuAS (0 = address strobe asserted)
	output        debug_cpu_dtack,    // _cpuDTACK (0 = acknowledged)

	// Serial port (SCC Channel A)
	output        serial_txd,       // SCC Channel A TX output (for sim-side RX)
	input         serial_rxd,       // SCC Channel A RX input (from sim-side TX)

	// Machine configuration inputs
	input  [1:0]  cfg_cpuType,      // Unused, kept for sim_main.cpp compatibility
	input  [2:0]  cfg_memSize,      // --ram: 0=4MB 1=8MB 2=20MB 3=36MB 4=68MB
	input  [1:0]  cfg_sdramMod,     // --sdram-module: emulated module 1=32MB 2=64MB 3=128MB
	input         nmi_pulse         // --nmi-at-frame: pulse a Level-7 NMI (MacsBug test)
);

	localparam SCSI_DEVS = 2;

	// Configuration
	localparam [1:0] status_cpu = 2'b10;     // 68020
	// Mac LC always runs at C15M (~15.67 MHz) - use 16 MHz clock enables

	////////////////////   CLOCKS   ///////////////////

	// Clock generation (clk_sys is 32MHz from testbench)
	wire clk_mem = clk_sys;  // Use same clock for memory
	wire pll_locked = !reset;

	// Clock enables - generated by addrController_top
	wire clk8_en_p, clk8_en_n;
	// V8 SCSI_PCLK / SCC RTxC source — see rtl/v8_clocks.sv (plan_040526.md Step 5).
	wire scsi_pclk_en;
	v8_clocks v8_clocks_inst (
		.clk_sys     (clk_sys),
		.reset       (~n_reset),
		.scsi_pclk_en(scsi_pclk_en)
	);
	wire clk16_en_p, clk16_en_n;
	wire clk8;

	// Reset logic
	// NOTE: Do NOT include _cpuReset_o here! The RESET instruction drives
	// reset_n low to reset peripherals, but should NOT reset the CPU itself.
	// IMPORTANT: In simulation, wait for ROM download to complete before releasing reset
	reg n_reset = 0;
	reg n_reset_prev = 0;
	reg dio_download_prev = 0;
	always @(posedge clk_sys) begin
		reg [15:0] rst_cnt;

		if (clk8_en_p) begin
			n_reset_prev <= n_reset;
			dio_download_prev <= dio_download;

			// Debug: track when download completes
			if (dio_download_prev && !dio_download) begin
				$display("[F%0d] SIM: dio_download went LOW - ROM download complete", sim_frame_count);
			end

			if(~pll_locked || reset || dio_download) begin
				rst_cnt <= '1;
				n_reset <= 0;
			end
			else if(rst_cnt) begin
				rst_cnt <= rst_cnt - 1'd1;
				// Debug: show countdown at key points only
				if (rst_cnt == 16'h0001) begin
					$display("[F%0d] SIM: rst_cnt about to expire, n_reset will go high", sim_frame_count);
				end
			end
			else begin
				n_reset <= 1;
			end

			// Debug: track when n_reset changes
			if (n_reset != n_reset_prev) begin
				$display("[F%0d] SIM: *** n_reset changed to %b *** (rst_cnt=%04x)", sim_frame_count, n_reset, rst_cnt);
			end
		end
	end

	///////////////////////////////////////////////////

	wire v8_ce_pix;

	// Display source select: run with +mdc824 to route the CARD's scanout to
	// the sim display (built-in video stays the default). NOTE: this no
	// longer touches the monitor sense — montype 7 ("no display") WEDGES the
	// ROM in early POST (MAME-proven with :vasp:MONTYPE forced: F2400 loop
	// at $4084xxxx, zero slot traffic). Sense stays 6; the card becomes the
	// boot display the real-hardware way, via the PRAM main-display setting.
	reg disp_mdc824 = 1'b0;
	initial disp_mdc824 = ($test$plusargs("mdc824") != 0);

	assign CE_PIXEL  = disp_mdc824 ? mdc_ce_pixel : v8_ce_pix;

	// Video Output — built-in (V8-heritage) video or the mdc824 card.
	// Card vga_blank is a display-enable (1 = visible); sim wants
	// active-high blanking on HB/VB, so invert (lbmactwo sim pattern).
	assign VGA_R  = disp_mdc824 ? mdc_r : v8_vga_r;
	assign VGA_G  = disp_mdc824 ? mdc_g : v8_vga_g;
	assign VGA_B  = disp_mdc824 ? mdc_b : v8_vga_b;
	wire VGA_DE = disp_mdc824 ? mdc_blank : v8_de;
	assign VGA_VS = disp_mdc824 ? mdc_vs : v8_vsync;
	assign VGA_HS = disp_mdc824 ? mdc_hs : v8_hsync;
	assign VGA_HB = disp_mdc824 ? ~mdc_blank : v8_hblank;
	assign VGA_VB = disp_mdc824 ? ~mdc_blank : v8_vblank;

	// Frame counter for debug logging
	reg [31:0] sim_frame_count = 0;
	reg vs_prev = 0;
	always @(posedge clk_sys) begin
		vs_prev <= VGA_VS;
		if (VGA_VS && !vs_prev)  // Rising edge of vsync = new frame
			sim_frame_count <= sim_frame_count + 1;
	end

	// ASC samples drive AUDIO_L/R directly (Commit C). Legacy DMA gone.
	assign AUDIO_L = asc_sample_l;
	assign AUDIO_R = asc_sample_r;

	// Macintosh IIvi memory configuration — VASP model: one contiguous block
	// at $0 (docs/VASP_RETARGET.md). Default (--ram absent) stays the 4MB base
	// config for the fastest RAM march during boot bring-up. Unlike MacIIvi.sv
	// there is deliberately NO sdram_sz clamp here: the sim runs any RAM size
	// against any emulated module (cfg_sdramMod -> sim_ram) so the oversized-
	// config corruption can be reproduced on purpose.
	wire [26:0] ram_size_bytes = (cfg_memSize == 3'd5) ? 27'h4400000 :  // 68MB
	                             (cfg_memSize == 3'd4) ? 27'h3000000 :  // 48MB
	                             (cfg_memSize == 3'd3) ? 27'h2400000 :  // 36MB
	                             (cfg_memSize == 3'd2) ? 27'h1400000 :  // 20MB
	                             (cfg_memSize == 3'd1) ? 27'h0800000 :  // 8MB
	                                                     27'h0400000;   // 4MB

	// Serial Ports - connect SCC Channel A to sim via serial_txd/serial_rxd ports
	wire serialOut;              // SCC Channel A TX (driven by SCC)
	wire serialIn = serial_rxd;  // SCC Channel A RX (driven by sim)
	wire serialCTS = 1'b0;
	wire serialRTS;
	assign serial_txd = serialOut;

	// V8 Video system wires
	wire v8_hsync, v8_vsync, v8_hblank, v8_vblank, v8_de;
	wire [7:0] v8_vga_r, v8_vga_g, v8_vga_b;
	wire [7:0] ariel_pixel_addr;
	wire [23:0] ariel_palette_data;
	wire [7:0] ariel_reg_dout;
	wire selectVDAC;       // From address decoder (VASP-internal CLUT/DAC)
	wire selectPseudoVIA;  // From address decoder
	wire selectVRAM;       // From address decoder
	wire selectBoxID;      // $5FFFFFFC machine-ID longword
	wire selectSuperSlot;  // NuBus $C/$D/$E super-slot space
	wire selectSlot;       // NuBus $FC/$FD/$FE slot space
	wire [1:0] slotNum;    // 0=$C 1=$D 2=$E
	// NuBus slot $E (mdc824) — keep in sync with MacIIvi.sv
	wire [15:0] nubusDataOut;
	wire        nubusAck_n;
	wire        nubus_nmrq_n;
	wire [7:0] pseudovia_dout;
	wire pseudovia_irq;
	wire capslock;

	// interconnects
	// CPU
	wire _cpuReset, _cpuReset_o, _cpuUDS, _cpuLDS, _cpuRW, _cpuAS;
	wire _cpuVMA, _cpuVPA, _cpuDTACK;
	wire E_rising, E_falling;
	wire [2:0] _cpuIPL;       // final IPL to CPU (Level-7 NMI applied below)
	wire [2:0] _cpuIPL_dc;    // raw IPL from dataController (VIA1 / PseudoVIA / SCC)
	wire [2:0] cpuFC;
	wire [7:0] cpuAddrHi;
	wire [31:0] cpuAddr;
	assign cpuAddr[0] = 1'b0;
	wire [7:0]  cpuAddrFullHi = cpuAddr[31:24];
	wire [15:0] cpuDataOut;

	// RAM/ROM
	wire _romOE;
	wire _ramOE, _ramWE;
	wire _memoryUDS, _memoryLDS;
	wire dioBusControl;
	wire cpuBusControl;
	wire [25:0] memoryAddr;  // 26-bit SDRAM word address from address controller
	wire [15:0] memoryDataOut;
	wire memoryLatch;
	// peripherals
	wire vid_alt;
	wire memoryOverlayOn, selectSCSI, selectSCC, selectIWM, selectVIA, selectRAM, selectROM, selectUnmapped;
	wire selectSCSIDMA;   // SCSI pseudo-DMA window (DACK) from address decoder
	wire scsiDREQ;        // SCSI pseudo-DMA request → gates CPU DTACK on DMA cycles
	wire scsiIRQ;         // NCR5380 latched IRQ (level) → pseudo-VIA IFR bit 3
	wire [15:0] dataControllerDataOut;

	// floppy disk image interface
	wire dskReadAckInt;
	wire [21:0] dskReadAddrInt;
	wire dskReadAckExt;
	wire [21:0] dskReadAddrExt;

	// dtack generation for 16 MHz mode
	reg  dtack_en, mem_latch_d;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			dtack_en <= 0;
		end
		else begin
			// mem_latch_d = registered memoryLatch: high at busPhase 0, i.e. the
			// START of each busCycle. (cpuBusControl & mem_latch_d) therefore
			// strobes once at the start of EVERY cpu slot.
			mem_latch_d <= memoryLatch;
			if (_cpuAS) dtack_en <= 0;
			// VRAM is SDRAM-backed and reads via the same cpu-slot as RAM,
			// so it must take the slot-aligned DTACK path (a cpu-slot start),
			// NOT the immediate !ROM&!RAM peripheral path. Excluding selectVRAM
			// here stops DTACK asserting before the SDRAM cpu-slot commits the
			// read/write (was truncating longword writes / sampling stale data).
			// H1: this was `!cpuBusControl_d & cpuBusControl` (rising edge), which
			// gave each ISOLATED cpu slot one DTACK opportunity. With slot 00 now
			// also a cpu slot the three slots are contiguous (one rising edge per
			// round), so we strobe at each cpu-slot start instead — same busPhase-0
			// timing as the old edge, but for all 3 slots (3 acks/round = +50%).
			if (!_cpuAS & ((cpuBusControl & mem_latch_d) | (!selectROM & !selectRAM & !selectVRAM))) dtack_en <= 1;
		end
	end

`ifdef PMMU_TRACE
	// DTACK-side probe (pairs with the PMMU walker probe in tg68k.v). Counts, per
	// ~262k-cycle window, how often the dtack_en SET condition's terms are true,
	// to explain why a stalled walker read never gets DTACK. During the stall the
	// last windows show the frozen picture.
	reg [31:0] dbg_dcyc, c_aslow, c_slot, c_setcond, c_den, c_selram;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			dbg_dcyc<=0; c_aslow<=0; c_slot<=0; c_setcond<=0; c_den<=0; c_selram<=0;
		end else begin
			dbg_dcyc <= dbg_dcyc + 1'b1;
			if (!_cpuAS)                                     c_aslow   <= c_aslow + 1'b1;
			if (cpuBusControl && mem_latch_d)                c_slot    <= c_slot + 1'b1;
			if (!_cpuAS && cpuBusControl && mem_latch_d)     c_setcond <= c_setcond + 1'b1;
			if (dtack_en)                                    c_den     <= c_den + 1'b1;
			if (selectRAM)                                   c_selram  <= c_selram + 1'b1;
			if (dbg_dcyc[17:0] == 18'd0) begin
				$display("DTACK WIN cyc=%0d aslow=%0d slot=%0d setcond=%0d den=%0d selram=%0d cpuAddr=%h selROM=%b selVRAM=%b dtack=%b @%0t",
				         dbg_dcyc, c_aslow, c_slot, c_setcond, c_den, c_selram, cpuAddr, selectROM, selectVRAM, _cpuDTACK, $time);
				c_aslow<=0; c_slot<=0; c_setcond<=0; c_den<=0; c_selram<=0;
			end
		end
	end
`endif

	// FC=7 is the 68k CPU space. cpuAddr[19:16] is the CPU-space cycle-type field:
	//   $F = interrupt acknowledge  -> autovector via VPA (Mac autovectored IRQs)
	//   else ($0 breakpoint, $2 coprocessor, ...) = no responder -> bus error.
	wire        fc7_iack = (cpuFC == 3'b111) && (cpuAddr[19:16] == 4'hF);
	wire        fc7_berr = (cpuFC == 3'b111) && !fc7_iack;
	// VASP 32-bit regions — keep both tops identical (rationale in MacIIvi.sv):
	//   io_space  = $50xxxxxx VASP I/O -> VPA/E-clock (except SCSI pseudo-DMA)
	//   slot_space = NuBus slot/super-slot space; open-bus $FFFF until the
	//   arbiter+mdc824 integration replaces this.
	wire        io_space   = (cpuAddrFullHi == 8'h50);
	wire        slot_space = selectSuperSlot || selectSlot;
	assign      _cpuVPA = fc7_iack ? 1'b0 : ((fc7_berr || slot_space) ? 1'b1 : ~(!_cpuAS && io_space && !selectSCSIDMA));
	assign      _cpuDTACK = fc7_berr ? 1'b1 :
	                        (slot_space && !_cpuAS) ? nubusAck_n :
	                        selectSCSIDMA ? ~scsiDREQ :
	                        (~(!_cpuAS && !io_space) | !dtack_en);

	// Peripheral (VPA) read-data register — mirror of MacIIvi.sv periph_din_reg
	// (fit-stabilization for the deep SCSI-CSR read cone; ported from MacLC
	// 0c8844b). Functionally transparent: VPA reads latch at s_state 6, ≥5
	// clk_sys after select settle, absorbing the +1 register latency. Mirrored
	// here so the sim exercises the registered path rather than trusting that
	// transparency claim FPGA-only.
	wire vpa_periph_read = !fc7_iack && !fc7_berr && !slot_space && !_cpuAS &&
	                       io_space && !selectSCSIDMA;
	reg [15:0] periph_din_reg;
	always @(posedge clk_sys) periph_din_reg <= dataControllerDataOut;
	wire [15:0] cpu_din_muxed = slot_space      ? nubusDataOut :
	                            vpa_periph_read ? periph_din_reg :
	                                              dataControllerDataOut;

	// Programmer's switch / Level-7 NMI — mirror of MacIIvi.sv (there the trigger is
	// the "R5" OSD button status[5]; in sim it is the nmi_pulse input driven by
	// --nmi-at-frame). Verifies the level-7 autovector path our CPU+glue takes.
	reg        nmi_req   = 1'b0;
	reg        nmi_btn_d = 1'b0;
	reg [15:0] nmi_to    = 16'd0;
	always @(posedge clk_sys) begin
		nmi_btn_d <= nmi_pulse;
		if (nmi_pulse && !nmi_btn_d) begin
			nmi_req <= 1'b1;
			nmi_to  <= 16'hFFFF;
			$display("[F%0d] NMI: asserted (Level-7 requested)", sim_frame_count);
		end else if (nmi_req) begin
			if ((fc7_iack && cpuAddr[3:1] == 3'b111) || nmi_to == 16'd0) begin
				nmi_req <= 1'b0;
				$display("[F%0d] NMI: cleared (%s)", sim_frame_count,
					(fc7_iack && cpuAddr[3:1] == 3'b111) ? "level-7 IACK TAKEN" : "timeout");
			end else
				nmi_to <= nmi_to - 1'b1;
		end
	end
	assign _cpuIPL = nmi_req ? 3'b000 : _cpuIPL_dc;

	wire        cpu_en_p      = clk16_en_p;
	wire        cpu_en_n      = clk16_en_n;
	assign      _cpuReset_o   = tg68_reset_n;

	// RESET-instruction soft peripheral reset (2026-08-08, ported from the
	// MacLC release-warm-restart-fix branch): both guest restart flavors
	// execute RESET + jump with NO Egret reset, and on real hardware that
	// instruction drives the external reset line. Stretch the CPU's pulse
	// to 16 clk for via6522 + the TIP latch (dataController), the pseudovia
	// INTERRUPT state, the ASC, and the SWIM (the LC's decisive wedge: a
	// warm boot inheriting ISM mode spins forever in the ROM's ISM->IWM
	// switch-back poll). Deliberately NOT the system reset (see the reset
	// NOTE above) and NOT the NCR/SCC (their setup must survive the ROM's
	// own T+4s RESET; resetting them regressed cold boot on the LC).
	reg [3:0] softrst_cnt = 4'd0;
	always @(posedge clk_sys) begin
		if (!_cpuReset_o)           softrst_cnt <= 4'hF;
		else if (softrst_cnt != 0)  softrst_cnt <= softrst_cnt - 1'd1;
	end
	wire soft_periph_rst = (softrst_cnt != 0);
	assign      _cpuRW        = tg68_rw;
	assign      _cpuAS        = tg68_as_n;
	assign      _cpuUDS       = tg68_uds_n;
	assign      _cpuLDS       = tg68_lds_n;
	assign      E_falling     = tg68_E_falling;
	assign      E_rising      = tg68_E_rising;
	assign      _cpuVMA       = tg68_vma_n;
	assign      cpuFC[0]      = tg68_fc0;
	assign      cpuFC[1]      = tg68_fc1;
	assign      cpuFC[2]      = tg68_fc2;
	assign      cpuAddr[31:1] = tg68_a[31:1];
	assign      cpuDataOut    = tg68_dout;

	wire        tg68_rw;
	wire        tg68_as_n;
	wire        tg68_uds_n;
	wire        tg68_lds_n;
	wire        tg68_E_rising;
	wire        tg68_E_falling;
	wire        tg68_vma_n;
	wire        tg68_fc0;
	wire        tg68_fc1;
	wire        tg68_fc2;
	wire [15:0] tg68_dout;
	wire [31:0] tg68_a;
	wire        tg68_reset_n;
	wire        tg68_longword;   // 32-bit access flag — drives SCSI pseudo-DMA byte packing
	wire [1:0]  tg68_busstate;

	// BERR: autovector path only for now. Unmapped-BERR disabled — see
	// docs/plan_040526.md: enabling it regresses boot because the CPU
	// emits high-bit addresses ($50xxxxxx etc.) early in ROM execution.
	// Bus-error CPU-space (FC=7) accesses that are NOT interrupt acknowledges:
	// the boot ROM's hardware-presence probes (`moves` to CPU space) which a real
	// 68030 faults because nothing decodes the cycle.
	// Slot-space: ACK with $FFFF (NuBus open-bus, the LBMacTwo
	// empty-slot mechanism) — TG68 berr is not handler-recoverable for
	// normal cycles. Keep both tops identical (MacIIvi.sv has the rationale).
	// Pseudo-DMA stall timeout → BERR — mirror of MacIIvi.sv (rationale there).
	localparam SDMA_TIMEOUT = 23'd8125000;  // ~250 ms @ 32.5 MHz
	reg [22:0] sdma_stall_ctr = 23'd0;
	reg        sdma_berr      = 1'b0;
	always @(posedge clk_sys) begin
		if (!_cpuReset) begin
			sdma_stall_ctr <= 0;
			sdma_berr      <= 0;
		end else if (_cpuAS) begin
			sdma_stall_ctr <= 0;
			sdma_berr      <= 0;
		end else if (selectSCSIDMA && !scsiDREQ && !sdma_berr) begin
			sdma_stall_ctr <= sdma_stall_ctr + 23'd1;
			if (sdma_stall_ctr == SDMA_TIMEOUT) begin
				sdma_berr <= 1'b1;   // held until AS deasserts
`ifdef SIMULATION
				$display("SDMA_BERR_TIMEOUT: addr=%h @%0t", cpuAddr, $time);
`endif
			end
		end else if (selectSCSIDMA)
			sdma_stall_ctr <= 0;
	end

	wire cpu_berr = (fc7_berr && !_cpuAS) || sdma_berr;
`ifdef SIMULATION
	reg _cpuAS_d;
	always @(posedge clk_sys) _cpuAS_d <= _cpuAS;
	always @(posedge clk_sys) begin
`ifdef VERBOSE_TRACE
		if (_cpuAS_d && !_cpuAS && cpuBusControl && selectUnmapped)
			$display("[F%0d] BERR_UNMAPPED: addr=%h fc=%b rw=%b", sim_frame_count, cpuAddr, cpuFC, _cpuRW);
		if (_cpuAS_d && !_cpuAS && |cpuAddrFullHi)
			$display("[F%0d] HIGH_ADDR: hi=%h addr=%h fc=%b rw=%b", sim_frame_count, cpuAddrFullHi, cpuAddr, cpuFC, _cpuRW);
`endif
	end
`endif

	tg68k tg68k (
		.clk        ( clk_sys      ),
		.reset      ( !_cpuReset ),
		.phi1       ( cpu_en_p  ),
		.phi2       ( cpu_en_n  ),
		.cpu        ( 2'b10 ),  // 68030 (Mac LC II); old selectable form: {status_cpu[1], |status_cpu}

		.dtack_n    ( _cpuDTACK  ),
		.rw_n       ( tg68_rw    ),
		.as_n       ( tg68_as_n  ),
		.uds_n      ( tg68_uds_n ),
		.lds_n      ( tg68_lds_n ),
		.fc         ( { tg68_fc2, tg68_fc1, tg68_fc0 } ),
		.reset_n    ( tg68_reset_n ),

		.E          (  ),
		.E_div      ( 1'b1 ),
		.E_PosClkEn ( tg68_E_falling ),
		.E_NegClkEn ( tg68_E_rising  ),
		.vma_n      ( tg68_vma_n ),
		.vpa_n      ( _cpuVPA ),

		.br_n       ( 1'b1    ),
		.bg_n       (  ),
		.bgack_n    ( 1'b1 ),

